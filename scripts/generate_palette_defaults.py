#!/usr/bin/env python3
"""Generate the firmware default palette from a theme file.

The Omega theme engine bakes colors into ``Palette::`` constants at build time.
Omega Lite needs the same colours as 8-bit RGB values for its customization
page, so this script extracts the 16 customizable roles from the theme and
writes a small header. Keeping the values 8-bit (instead of reading back the
RGB565 ``Palette::`` constants) means the HEX shown in the settings matches the
theme file exactly.

Usage:
    python3 scripts/generate_palette_defaults.py \
        --theme themes/omega_lite.json \
        --output apps/settings/custom_colors/palette_defaults_generated.h
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from palette_schema import ROLE_PALETTE_KEYS  # noqa: E402

HEADER_TEMPLATE = """// Generated by scripts/generate_palette_defaults.py.
// Source theme: {theme}
// Do not edit by hand: run the script again after changing the theme.
#ifndef OMEGA_LITE_CUSTOM_COLORS_PALETTE_DEFAULTS_GENERATED_H
#define OMEGA_LITE_CUSTOM_COLORS_PALETTE_DEFAULTS_GENERATED_H

#include "color_roles.h"
#include "color_rgb.h"

namespace OmegaLite {{
namespace Colors {{

// Defaults of the customizable roles, in Role order.
constexpr RgbColor k_themeDefaultColors[k_numberOfRoles] = {{
{entries}
}};

}} // namespace Colors
}} // namespace OmegaLite

#endif
"""


def flatten_colors(colors, prefix=""):
    flat = {}
    for name, value in colors.items():
        if name == "":
            path = prefix
        else:
            path = name if not prefix else f"{prefix}.{name}"
        if isinstance(value, dict):
            flat.update(flatten_colors(value, path))
        else:
            flat[path] = value
    return flat


def build_header(theme_path):
    with open(theme_path, "r", encoding="utf-8") as handle:
        theme = json.load(handle)
    flat = flatten_colors(theme["colors"])
    lines = []
    for role, key in ROLE_PALETTE_KEYS.items():
        try:
            value = flat[key]
        except KeyError:
            raise SystemExit(f"error: theme has no color {key!r} for role {role}")
        if len(value) != 6:
            raise SystemExit(f"error: {key}: {value!r} is not a six digit color")
        lines.append(
            f"  // {role} ({key})\n"
            f"  RgbColor(0x{value[0:2]}, 0x{value[2:4]}, 0x{value[4:6]}),"
        )
    return HEADER_TEMPLATE.format(theme=Path(theme_path).name, entries="\n".join(lines))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--theme", default="themes/omega_lite.json")
    parser.add_argument("--output", default="apps/settings/custom_colors/palette_defaults_generated.h")
    parser.add_argument("--check", action="store_true", help="fail if the header is out of date")
    args = parser.parse_args(argv)

    content = build_header(args.theme)
    output = Path(args.output)
    if args.check:
        try:
            current = output.read_text(encoding="utf-8")
        except FileNotFoundError:
            print(f"error: {output} is missing", file=sys.stderr)
            return 1
        if current != content:
            print(f"error: {output} is out of date", file=sys.stderr)
            return 1
        print(f"OK      {output}")
        return 0
    output.write_text(content, encoding="utf-8")
    print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
