#!/usr/bin/env python3
"""Generate a runtime Omega palette from a theme file.

Drop-in replacement for ``themes/themes_manager.py`` when generating
``escher/palette.h``: same arguments, same member names, but every ``Palette``
member becomes a mutable ``KDColor`` instead of a ``constexpr`` constant, so
colors can change at runtime without rebuilding.

    generate_runtime_palette.py <repo> <theme> <output header> <build dir>

It writes two files:

* ``<output header>``      - ``ThemeDefaults`` (compile-time theme values) and
                             ``Palette`` (mutable members + reset function);
* ``palette_definitions.inc`` next to it - the definitions, the
                             ``resetToThemeDefaults()`` implementation and
                             ``nextDataColor()``, included by
                             ``escher/src/palette.cpp``.

``ThemeDefaults`` keeps the theme values available as constants: Omega and
Omega Lite use them to restore the palette, and they document what the theme
asked for even after a user override.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Colors that are not part of the theme file but are referenced everywhere in
# Omega. Values are the upstream ones from themes/themes_manager.py.
EXTRA_COLORS = [
    ("YellowDark", "ffb734"),
    ("YellowLight", "ffcc7b"),
    ("PurpleBright", "656975"),
    ("PurpleDark", "414147"),
    ("GrayWhite", "f5f5f5"),
    ("GrayBright", "ececec"),
    ("GrayMiddle", "d9d9d9"),
    ("GrayDark", "a7a7a7"),
    ("GrayVeryDark", "8c8c8c"),
    ("Select", "d4d7e0"),
    ("SelectDark", "b0b8d8"),
    ("WallScreen", "f7f9fa"),
    ("WallScreenDark", "e0e6ed"),
    ("SubTab", "b8bbc5"),
    ("LowBattery", "f30211"),
    ("Red", "ff000c"),
    ("RedLight", "fe6363"),
    ("Magenta", "ff0588"),
    ("Turquoise", "60c1ec"),
    ("Pink", "ffabb6"),
    ("Blue", "5075f2"),
    ("BlueLight", "718fee"),
    ("Orange", "fe871f"),
    ("Green", "50c102"),
    ("GreenLight", "52db8f"),
    ("Brown", "8d7350"),
    ("Purple", "6e2d79"),
    ("BlueishGrey", "919ea4"),
]

ALIASES = [("Cyan", "KDColorBlue")]

DATA_COLORS = ["Red", "Blue", "Green", "YellowDark", "Magenta", "Turquoise", "Pink", "Orange"]
DATA_COLORS_LIGHT = ["RedLight", "BlueLight", "GreenLight", "YellowLight"]
ATOM_COLORS = [
    "AtomUnknown", "AtomAlkaliMetal", "AtomAlkaliEarthMetal", "AtomLanthanide",
    "AtomActinide", "AtomTransitionMetal", "AtomPostTransitionMetal", "AtomMetalloid",
    "AtomHalogen", "AtomReactiveNonmetal", "AtomNobleGas",
]


def flatten_theme_colors(colors, prefix=""):
    """Return [(member name, hex value)] in theme order."""
    entries = []
    for name, value in colors.items():
        if name == "":
            member = prefix
        else:
            member = name if not prefix else prefix + name
        if isinstance(value, dict):
            entries.extend(flatten_theme_colors(value, member))
        else:
            entries.append((member, value))
    return entries


def resolve_theme_path(repo, theme, omega_root):
    if repo == "local":
        return omega_root / "themes" / "themes" / "local" / f"{theme}.json"
    folder = Path(repo.rstrip("/")).name
    if folder.endswith(".git"):
        folder = folder[:-4]
    return omega_root / "themes" / "themes" / "git" / folder / f"{theme}.json"


def color_expression(name, value):
    if value is None:
        return name
    return f"KDColor::RGB24(0x{value})"


def build(theme_path):
    with open(theme_path, "r", encoding="utf-8") as handle:
        theme = json.load(handle)
    entries = flatten_theme_colors(theme["colors"])
    if not entries:
        raise SystemExit(f"error: {theme_path} has no colors")
    for member, value in entries:
        if len(value) != 6:
            raise SystemExit(f"error: {member}: {value!r} is not a six digit color")

    header = []
    header.append("/* Generated by scripts/generate_runtime_palette.py.")
    header.append(f" * Theme: {Path(theme_path).name} ({theme.get('name', '?')}).")
    header.append(" * Do not edit: regenerate from the theme instead.")
    header.append(" *")
    header.append(" * Palette members are runtime variables so that colors can be changed")
    header.append(" * without recompiling. ThemeDefaults keeps the theme values as constants. */")
    header.append("#ifndef ESCHER_PALETTE_H")
    header.append("#define ESCHER_PALETTE_H")
    header.append("")
    header.append("#include <kandinsky/color.h>")
    header.append("#include <stddef.h>")
    header.append("")
    header.append("class ThemeDefaults {")
    header.append("public:")
    for member, value in entries:
        header.append(f"  constexpr static KDColor {member} = {color_expression(member, value)};")
    for member, value in EXTRA_COLORS:
        header.append(f"  constexpr static KDColor {member} = {color_expression(member, value)};")
    header.append(f"  constexpr static KDColor Cyan = {ALIASES[0][1]};")
    header.append(f"  constexpr static KDColor DataColor[{len(DATA_COLORS)}] = {{"
                  + ", ".join(DATA_COLORS) + "};")
    header.append(f"  constexpr static KDColor DataColorLight[{len(DATA_COLORS_LIGHT)}] = {{"
                  + ", ".join(DATA_COLORS_LIGHT) + "};")
    header.append(f"  constexpr static KDColor AtomColor[{len(ATOM_COLORS)}] = {{"
                  + ", ".join(ATOM_COLORS) + "};")
    header.append("};")
    header.append("")
    header.append("class Palette {")
    header.append("public:")
    for member, _ in entries:
        header.append(f"  static KDColor {member};")
    for member, _ in EXTRA_COLORS:
        header.append(f"  static KDColor {member};")
    header.append("  static KDColor Cyan;")
    header.append(f"  static KDColor DataColor[{len(DATA_COLORS)}];")
    header.append(f"  static KDColor DataColorLight[{len(DATA_COLORS_LIGHT)}];")
    header.append(f"  static KDColor AtomColor[{len(ATOM_COLORS)}];")
    header.append("")
    header.append("  /* Restores every member from ThemeDefaults. */")
    header.append("  static void resetToThemeDefaults();")
    header.append("")
    header.append(f"  constexpr static size_t numberOfDataColors() {{ return {len(DATA_COLORS)}; }}")
    header.append("  constexpr static size_t numberOfLightDataColors() { return "
                  f"{len(DATA_COLORS_LIGHT)}; }}")
    header.append("  static KDColor nextDataColor(int * colorIndex);")
    header.append("};")
    header.append("")
    header.append("#endif")
    header_text = "\n".join(header) + "\n"

    definitions = []
    definitions.append("/* Generated by scripts/generate_runtime_palette.py. Do not edit. */")
    for member, _ in entries:
        definitions.append(f"KDColor Palette::{member} = ThemeDefaults::{member};")
    for member, _ in EXTRA_COLORS:
        definitions.append(f"KDColor Palette::{member} = ThemeDefaults::{member};")
    definitions.append("KDColor Palette::Cyan = ThemeDefaults::Cyan;")
    for array, values in (
        ("DataColor", DATA_COLORS),
        ("DataColorLight", DATA_COLORS_LIGHT),
        ("AtomColor", ATOM_COLORS),
    ):
        initialized = ", ".join(f"ThemeDefaults::{value}" for value in values)
        definitions.append(f"KDColor Palette::{array}[{len(values)}] = {{{initialized}}};")
    definitions.append("")
    definitions.append("/* C++11: the reset loop below indexes these arrays, which odr-uses")
    definitions.append(" * them, so each needs an out-of-class definition in one TU. */")
    for array, values in (
        ("DataColor", DATA_COLORS),
        ("DataColorLight", DATA_COLORS_LIGHT),
        ("AtomColor", ATOM_COLORS),
    ):
        definitions.append(f"constexpr KDColor ThemeDefaults::{array}[{len(values)}];")
    definitions.append("")
    definitions.append("void Palette::resetToThemeDefaults() {")
    for member, _ in entries:
        definitions.append(f"  {member} = ThemeDefaults::{member};")
    for member, _ in EXTRA_COLORS:
        definitions.append(f"  {member} = ThemeDefaults::{member};")
    definitions.append("  Cyan = ThemeDefaults::Cyan;")
    definitions.append("  for (size_t i = 0; i < numberOfDataColors(); i++) {")
    definitions.append("    DataColor[i] = ThemeDefaults::DataColor[i];")
    definitions.append("  }")
    definitions.append("  for (size_t i = 0; i < numberOfLightDataColors(); i++) {")
    definitions.append("    DataColorLight[i] = ThemeDefaults::DataColorLight[i];")
    definitions.append("  }")
    definitions.append(f"  for (size_t i = 0; i < {len(ATOM_COLORS)}; i++) {{")
    definitions.append("    AtomColor[i] = ThemeDefaults::AtomColor[i];")
    definitions.append("  }")
    definitions.append("}")
    definitions.append("")
    definitions.append("KDColor Palette::nextDataColor(int * colorIndex) {")
    definitions.append("  if (colorIndex == nullptr || *colorIndex < 0 ||")
    definitions.append("      static_cast<size_t>(*colorIndex) >= numberOfDataColors()) {")
    definitions.append("    return DataColor[0];")
    definitions.append("  }")
    definitions.append("  const KDColor color = DataColor[*colorIndex];")
    definitions.append("  *colorIndex = (*colorIndex + 1) % static_cast<int>(numberOfDataColors());")
    definitions.append("  return color;")
    definitions.append("}")
    definitions_text = "\n".join(definitions) + "\n"

    return header_text, definitions_text, len(entries)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Generate a runtime Omega palette.")
    parser.add_argument("repo", help="theme repository ('local' or a git URL)")
    parser.add_argument("theme", help="theme name")
    parser.add_argument("output", help="path of the palette.h to write")
    parser.add_argument("build_dir", nargs="?", default="", help="build directory (unused)")
    parser.add_argument("--omega-root", default=".", help="root of the Omega checkout")
    parser.add_argument("--theme-file", help="use this theme file instead of resolving repo/theme")
    parser.add_argument("--check", action="store_true", help="fail if the files are out of date")
    args = parser.parse_args(argv)

    theme_path = (Path(args.theme_file) if args.theme_file
                  else resolve_theme_path(args.repo, args.theme, Path(args.omega_root)))
    if not theme_path.is_file():
        raise SystemExit(f"error: theme file not found: {theme_path}")
    header, definitions, count = build(theme_path)

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    definitions_path = output.with_name("palette_definitions.inc")

    if args.check:
        current = output.read_text(encoding="utf-8") if output.is_file() else ""
        current_def = (definitions_path.read_text(encoding="utf-8")
                       if definitions_path.is_file() else "")
        if current != header or current_def != definitions:
            raise SystemExit("error: generated palette is out of date")
        print(f"OK      {output}")
        return 0

    output.write_text(header, encoding="utf-8")
    definitions_path.write_text(definitions, encoding="utf-8")
    print(f"Wrote {output} and {definitions_path} ({count} theme colors + {len(EXTRA_COLORS)} fixed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
